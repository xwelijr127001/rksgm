/**
 * T-010 (D-51/D-52): placeholder thumbnails for the Episode 2 rooms, generated from the EXISTING background WebPs with the same
 * toolchain as bangun-ilustrasi-auto2.mjs (ffmpeg libwebp). One 64 px wide WebP per location, quality 40, inlined as data URIs
 * in client/src/cerita/seni/auto-2/ilustrasi/kabur.ts (imported only by the AUTO-2 chunk; no network request).
 *
 *   node tools/cerita/bangun-kabur-auto2.mjs          (FFMPEG=<path> if ffmpeg is not on PATH)
 *
 * Recipe per location: ffmpeg -i <lokasi>-latar-1100.webp -vf "scale=64:-2:flags=area" -c:v libwebp -quality 40 -compression_level 6 out.webp
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';

const AKAR = path.resolve(path.dirname(new URL(import.meta.url).pathname.replace(/^\/([A-Za-z]:)/, '$1')), '..', '..');
const DIR = path.join(AKAR, 'client', 'src', 'cerita', 'seni', 'auto-2', 'ilustrasi');
const FFMPEG = process.env.FFMPEG || 'ffmpeg';
const manifest = JSON.parse(fs.readFileSync(path.join(DIR, 'ilustrasi.json'), 'utf8'));
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'kabur-'));
const keluar = {};
let total = 0;
for (const [lokasi, l] of Object.entries(manifest.latar)) {
  const sumber = l.gambar.find((g) => g.w === 1100) ?? l.gambar[0];
  const out = path.join(tmp, `${lokasi}.webp`);
  execFileSync(FFMPEG, ['-y', '-loglevel', 'error', '-i', path.join(DIR, sumber.berkas), '-vf', 'scale=64:-2:flags=area', '-c:v', 'libwebp', '-quality', '40', '-compression_level', '6', out]);
  const b = fs.readFileSync(out);
  total += b.length;
  keluar[lokasi] = 'data:image/webp;base64,' + b.toString('base64');
  console.log(`${lokasi}: ${sumber.berkas} -> ${b.length} B`);
}
fs.rmSync(tmp, { recursive: true, force: true });
const isi = `/* GENERATED by tools/cerita/bangun-kabur-auto2.mjs (T-010 D-52): 64 px WebP thumbnails of each location background, shown blurred
   as the stage placeholder until the real layers are decoded. ${total} B total. Do not edit by hand. */
export const KABUR_AUTO_2: Readonly<Record<string, string>> = ${JSON.stringify(keluar, null, 2)};
`;
fs.writeFileSync(path.join(DIR, 'kabur.ts'), isi);
console.log(`total ${total} B -> kabur.ts`);
